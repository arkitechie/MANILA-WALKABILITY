"""
winning_model.pkl + scaler.pkl  ->  model_gbm.js

Emits a faithful, dependency-free JavaScript port of the fitted
GradientBoostingRegressor (100 trees, depth 3) together with the *real* fitted
RobustScaler parameters, plus reference predictions so the browser can verify
the port against scikit-learn at runtime.
"""
import json, pathlib, warnings
warnings.filterwarnings('ignore')
import _shim  # noqa: F401
import joblib, numpy as np, h3

HERE = pathlib.Path(__file__).resolve().parent.parent
model = joblib.load(HERE / 'winning_model.pkl')
scaler = joblib.load(HERE / 'scaler.pkl')

names = list(model.feature_names_in_)
NF = model.n_features_in_
LR = float(model.learning_rate)
INIT = float(np.ravel(model._raw_predict_init(np.zeros((1, NF))))[0])

# ---------------------------------------------------------------- H3 audit --
raw = (HERE / 'data.js').read_text(encoding='utf-8')
payload = json.loads(raw[raw.index('{'):raw.rindex('}') + 1])
segments = payload['segments']
valid = sum(1 for r in segments if h3.is_valid_cell(r[2]))
print('H3 AUDIT: %d of %d h3_res9 values are valid H3 cells (%.1f%%)'
      % (valid, len(segments), 100 * valid / len(segments)))

# ------------------------------------------------------------------ trees --
trees = []
for est in model.estimators_[:, 0]:
    t = est.tree_
    trees.append({
        'f': [int(x) for x in t.feature],                       # -2 == leaf
        't': [round(float(x), 9) for x in t.threshold],
        'l': [int(x) for x in t.children_left],
        'r': [int(x) for x in t.children_right],
        'v': [round(float(x), 10) for x in t.value.reshape(-1)],
    })
total_nodes = sum(len(t['f']) for t in trees)

# ----------------------------------------------------------------- scaler --
center, scale = scaler.center_, scaler.scale_
assert np.all(center[12:] == 0) and np.all(scale[12:] == 1), 'one-hot block is not identity'
CENTER12 = [float(x) for x in center[:12]]
SCALE12 = [float(x) for x in scale[:12]]

# --------------------------------------------- rebuild the training matrix --
# so we can emit reference predictions the browser can check itself against.
cats = payload['categories']
enc = payload['encoders']
C = payload['constants']
blocks = {k: tuple(v) for k, v in payload['featureOrder']['blocks'].items()}
index_of = {n: i for i, n in enumerate(names)}


def minmax(v, lo, hi):
    return 0.0 if hi == lo else (v - lo) / (hi - lo)


def build_vector(osmid, name, h3c, highway, sidewalk, poi, dist, idn):
    x = np.zeros(NF)
    P = minmax(poi, *C['poi'])
    I = minmax(idn, *C['idn'])
    T = minmax(1.0 / dist, *C['inv'])
    rho = payload['rho'][highway][sidewalk]
    x[0] = enc['osmid'][osmid]
    x[1] = enc['name'][name]
    x[2] = enc['h3_res9'][h3c]
    x[3] = enc['highway'][highway]
    x[4] = enc['sidewalk'][sidewalk]
    x[5], x[6], x[7] = poi, dist, idn
    x[8], x[9], x[10], x[11] = P, T, I, rho
    for col, val in (('osmid', osmid), ('name', name), ('h3_res9', h3c),
                     ('highway', highway), ('sidewalk', sidewalk)):
        j = index_of.get(col + '_' + str(val))
        if j is not None:
            x[j] = 1.0
    return x


rows = [build_vector(r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7]) for r in segments]
X = np.asarray(rows)
Xs = scaler.transform(X)
pred = model.predict(Xs)
truth = np.array([r[8] for r in segments])
print('sklearn on training rows: R^2=%.6f  MAE=%.4f' %
      (1 - ((pred - truth) ** 2).sum() / ((truth - truth.mean()) ** 2).sum(),
       np.abs(pred - truth).mean()))


# ------------------------------------------------- pure-python mirror of JS --
def js_predict(xs):
    acc = INIT
    for t in trees:
        n = 0
        while t['l'][n] != -1:
            n = t['l'][n] if xs[t['f'][n]] <= t['t'][n] else t['r'][n]
        acc += LR * t['v'][n]
    return acc


mirror = np.array([js_predict(Xs[i]) for i in range(len(Xs))])
print('JS-mirror vs sklearn: max abs diff = %.3e' % np.abs(mirror - pred).max())
assert np.abs(mirror - pred).max() < 1e-6, 'port does not reproduce sklearn'

# 24 reference rows spread across the score range, for the in-browser self-test
order = np.argsort(truth)
picks = [int(order[i]) for i in np.linspace(0, len(order) - 1, 24).astype(int)]
refs = [{'i': p, 'y': round(float(pred[p]), 6)} for p in picks]

# ------------------------------------------------------------------ emit js --
out = ['/* ' + '=' * 74,
       '   model_gbm.js  —  generated by build/export_model.py. Do not hand-edit.',
       '',
       '   A faithful JavaScript port of winning_model.pkl:',
       '     sklearn.ensemble.GradientBoostingRegressor',
       '     n_estimators=%d  max_depth=%d  learning_rate=%s  max_features=%s' %
       (model.n_estimators, model.max_depth, model.learning_rate, model.max_features),
       '     %d features in, %d trees, %d nodes total' % (NF, len(trees), total_nodes),
       '',
       '   Bundled with the real fitted RobustScaler from scaler.pkl (columns 12+',
       '   are identity, so only the 12 numeric columns are actually transformed).',
       '',
       '   Verified against scikit-learn 1.6.1 on all %d training rows:' % len(segments),
       '   max absolute difference %.2e.' % np.abs(mirror - pred).max(),
       '   ' + '=' * 74 + ' */',
       '',
       '(function () {',
       "  'use strict';",
       '',
       '  var N_FEATURES = %d;' % NF,
       '  var INIT = %r;' % INIT,
       '  var LR = %r;' % LR,
       '',
       '  var CENTER = %s;' % json.dumps(CENTER12),
       '  var SCALE  = %s;' % json.dumps(SCALE12),
       '',
       '  /* Each tree is [feature[], threshold[], left[], right[], value[]].',
       '     feature === -2 marks a leaf. left === -1 also marks a leaf. */',
       '  var TREES = [']
for k, t in enumerate(trees):
    out.append('    [%s,%s,%s,%s,%s]%s' % (
        json.dumps(t['f'], separators=(',', ':')),
        json.dumps(t['t'], separators=(',', ':')),
        json.dumps(t['l'], separators=(',', ':')),
        json.dumps(t['r'], separators=(',', ':')),
        json.dumps(t['v'], separators=(',', ':')),
        ',' if k < len(trees) - 1 else ''))
out += ['  ];', '',
        '  var REFERENCE = %s;' % json.dumps(refs, separators=(',', ':')),
        '',
        '  /* RobustScaler: (x - center) / scale on the 12 numeric columns only. */',
        '  function scaleVector(x) {',
        '    var out = new Float64Array(x.length ? x : N_FEATURES);',
        '    for (var i = 0; i < x.length; i++) out[i] = x[i];',
        '    for (var j = 0; j < CENTER.length; j++) out[j] = (out[j] - CENTER[j]) / SCALE[j];',
        '    return out;',
        '  }',
        '',
        '  /* Sum of the boosted stumps on an already-scaled vector. */',
        '  function scoreScaled(x) {',
        '    if (!x || x.length !== N_FEATURES) {',
        '      throw new Error("model_gbm: expected a vector of length " + N_FEATURES);',
        '    }',
        '    var acc = INIT;',
        '    for (var k = 0; k < TREES.length; k++) {',
        '      var t = TREES[k], f = t[0], th = t[1], L = t[2], R = t[3], V = t[4], n = 0;',
        '      while (L[n] !== -1) n = (x[f[n]] <= th[n]) ? L[n] : R[n];',
        '      acc += LR * V[n];',
        '    }',
        '    return acc;',
        '  }',
        '',
        '  /* Convenience: takes an unscaled vector, applies the fitted scaler first. */',
        '  function score(x) { return scoreScaled(scaleVector(x)); }',
        '',
        '  window.MODEL_GBM = {',
        '    kind: "gbm",',
        '    label: "Gradient Boosting (ported from winning_model.pkl)",',
        '    note: "100 trees, depth 3. ~2,500 of its 2,513 inputs are one-hot row " +',
        '          "identifiers, which are all-zero for any street it was not trained on.",',
        '    nFeatures: N_FEATURES,',
        '    nTrees: TREES.length,',
        '    expectsScaled: true,',
        '    center: CENTER,',
        '    scale: SCALE,',
        '    scaleVector: scaleVector,',
        '    scoreScaled: scoreScaled,',
        '    score: score,',
        '    reference: REFERENCE',
        '  };',
        '})();',
        '']

(HERE / 'model_gbm.js').write_text('\n'.join(out), encoding='utf-8')
print('model_gbm.js written: %d trees, %d nodes, %.1f KB'
      % (len(trees), total_nodes, (HERE / 'model_gbm.js').stat().st_size / 1024))

(HERE / 'build' / 'scaler_params.json').write_text(
    json.dumps({'center': CENTER12, 'scale': SCALE12,
                'columns': names[:12]}, indent=1), encoding='utf-8')
print('scaler_params.json written')
